def conservative_ellipsoid_clearance(
    model: mujoco.MjModel,
    data: mujoco.MjData,
    robot_ellipsoids,
    obstacle_centers: np.ndarray,
    obstacle_shapes: np.ndarray,
    safety_margin: float,
    obstacle_offsets: np.ndarray | float = 0.0,
) -> float:
    positions, _, _, robot_shapes = ellipsoid_world_state(model, data, robot_ellipsoids)
    best = np.inf
    for position, robot_shape in zip(positions, robot_shapes):
        delta = obstacle_centers - position
        offsets = np.broadcast_to(np.asarray(obstacle_offsets, dtype=float), (len(obstacle_centers),))
        for obstacle_index, (obstacle_center, obstacle_shape) in enumerate(
            zip(obstacle_centers, obstacle_shapes)
        ):
            # Use the same support-optimal normal as the QP; a center-line
            # distance is not a valid separating-plane slack for ellipsoids.
            controller_normal = optimal_support_separating_normal(
                position, robot_shape, obstacle_center, obstacle_shape
            )
            robot_extent = support_radius(robot_shape, controller_normal)
            obstacle_extent = (
                support_radius(obstacle_shape, controller_normal)
                + offsets[obstacle_index]
            )
            clearance = (
                float(controller_normal @ (obstacle_center - position))
                - robot_extent
                - obstacle_extent
                - safety_margin
            )
            best = min(best, clearance)
    return float(best)


def integrate_ellipsoid_with_backtracking(
    model: mujoco.MjModel,
    data: mujoco.MjData,
    qdot: np.ndarray,
    robot_ellipsoids,
    obstacle_centers: np.ndarray,
    obstacle_shapes: np.ndarray,
    safety_margin: float,
    controller: EllipsoidLiuQPController,
) -> tuple[float, float]:
    q_before = data.qpos.copy()
    current_positions, _, _, current_shapes = ellipsoid_world_state(
        model, data, robot_ellipsoids
    )
    # Freeze the same valid separating planes used by the sequential QP.
    # Unlike a center-line support gap, their signed support slack is a true
    # sufficient non-intersection certificate for ellipsoids.
    frozen_planes: list[tuple[int, np.ndarray, float]] = []
    current = np.inf
    for robot_index, (position, shape) in enumerate(
        zip(current_positions, current_shapes)
    ):
        for plane in controller.prune_redundant_obstacle_ellipsoids(position, shape):
            normal = plane.normal_to_obstacle
            obstacle_index = plane.obstacle_index
            rhs = float(
                normal @ obstacle_centers[obstacle_index]
                - support_radius(obstacle_shapes[obstacle_index], normal)
                - controller.obstacle_offsets[obstacle_index]
                - safety_margin
            )
            frozen_planes.append((robot_index, normal.copy(), rhs))
            current = min(
                current,
                rhs - float(normal @ position) - support_radius(shape, normal),
            )
    for scale in (
        1.0,
        0.5,
        0.25,
        0.125,
        0.0625,
        0.03125,
        0.015625,
        0.0078125,
        0.00390625,
        0.001953125,
        0.0009765625,
        0.0,
    ):
        q_trial = q_before.copy()
        if scale:
            mujoco.mj_integratePos(model, q_trial, qdot, DT * scale)
        set_configuration(model, data, q_trial)
        trial_positions, _, _, trial_shapes = ellipsoid_world_state(
            model, data, robot_ellipsoids
        )
        clearance = min(
            (
                rhs
                - float(normal @ trial_positions[robot_index])
                - support_radius(trial_shapes[robot_index], normal)
                for robot_index, normal, rhs in frozen_planes
            ),
            default=np.inf,
        )
        world_contact = minimum_mujoco_world_contact(data, model)
        self_contact = minimum_mujoco_self_contact(data, model)
        exact_safe = world_contact >= -1.0e-7 and self_contact >= -1.0e-7
        threshold = -2.0e-5 if current >= -2.0e-5 else current - 1.0e-9
        if clearance >= threshold and exact_safe:
            return float(scale), float(clearance)
    set_configuration(model, data, q_before)
    return 0.0, float(current)


def _oscillation_rate(qdots: np.ndarray, threshold: float = 1.0e-3) -> float:
    if len(qdots) < 2:
        return 0.0
    valid = (np.abs(qdots[1:]) > threshold) & (np.abs(qdots[:-1]) > threshold)
    flips = valid & (np.sign(qdots[1:]) != np.sign(qdots[:-1]))
    return float(np.sum(flips) / max(np.sum(valid), 1))


def run_scene(
    scene: SceneDefinition,
    certificate: str,
    guidance: str = "direct",
    robot_geometry: str = "sphere-limit",
    objective_dither_std: float = 0.0,
    objective_dither_seed: int = 0,
    pointcloud_cluster_size: float = 0.040,
    pointcloud_maximum_overshoot: float = 0.020,
    pointcloud_point_spacing: float = 0.012,
    pointcloud_filter_size: float = 0.012,
    apply_surface_cover: bool = True,
    duration_override: float | None = None,
    pointcloud_proxies_override: PointCloudProxySet | None = None,
    pointcloud_output_tag: str = "",
    goal_tolerance: float = 0.018,
    guidance_targets_override: list[np.ndarray] | None = None,
    guidance_switch_tolerance: float = 0.035,
    target_source_override: str | None = None,
) -> dict[str, float | int | str | bool | None]:
    geometry_suffix = "_full_robot" if robot_geometry == "full-ellipsoid" else ""
    uses_pointcloud = scene.name.startswith(
        ("shelf_drawer", "fastiris_", "incremental_drawer")
    )
    cluster_suffix = "_pca_graph_mahal" if uses_pointcloud else ""
    if uses_pointcloud and not np.isclose(pointcloud_cluster_size, 0.040):
        cluster_suffix += f"_cluster{int(round(1000.0 * pointcloud_cluster_size)):03d}mm"
    if uses_pointcloud and not np.isclose(pointcloud_maximum_overshoot, 0.020):
        cluster_suffix += (
            f"_over{int(round(1000.0 * pointcloud_maximum_overshoot)):03d}mm"
        )
    if uses_pointcloud and not np.isclose(pointcloud_point_spacing, 0.012):
        cluster_suffix += f"_pc{int(round(1000.0 * pointcloud_point_spacing)):03d}mm"
    if uses_pointcloud and not np.isclose(pointcloud_filter_size, 0.012):
        cluster_suffix += f"_vox{int(round(1000.0 * pointcloud_filter_size)):03d}mm"
    if uses_pointcloud and apply_surface_cover:
        cluster_suffix += "_surfacecover"
    if pointcloud_output_tag:
        cluster_suffix += f"_{pointcloud_output_tag}"
    if not np.isclose(goal_tolerance, 0.018):
        cluster_suffix += f"_goal{int(round(1000.0 * goal_tolerance)):03d}mm"
    run_duration = scene.duration if duration_override is None else float(duration_override)
    if duration_override is not None and not np.isclose(run_duration, scene.duration):
        cluster_suffix += f"_dur{int(round(run_duration)):03d}s"
    output_dir = RESULTS_ROOT / (
        f"{scene.name}_{certificate}{geometry_suffix}_{guidance}{cluster_suffix}"
    )
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "scene.xml").write_text(build_xml(scene), encoding="utf-8")

    model = build_model(scene)
    data = mujoco.MjData(model)
    set_configuration(model, data, np.asarray(scene.q0))
    pointcloud_proxies = None
    obstacle_index = None
    if uses_pointcloud and pointcloud_proxies_override is None:
        pointcloud_proxies = build_shelf_drawer_proxy_set(
            scene.boxes,
            point_spacing=pointcloud_point_spacing,
            filter_size=pointcloud_filter_size,
            cluster_size=pointcloud_cluster_size,
            maximum_aabb_overshoot=pointcloud_maximum_overshoot,
        )
    elif uses_pointcloud:
        pointcloud_proxies = pointcloud_proxies_override
    proxy_offsets = None
    if pointcloud_proxies is not None:
        if pointcloud_proxies.proxy_offset_radii is not None:
            proxy_offsets = np.asarray(
                pointcloud_proxies.proxy_offset_radii, dtype=float
            )
        else:
            proxy_offsets = np.full(
                len(pointcloud_proxies.centers),
                pointcloud_proxies.surface_cover_radius,
            )
    if certificate == "sphere":
        robot_proxies = build_robot_certificate(model)
        if scene.name == "robust_slot":
            obstacle_centers, obstacle_params, _ = sample_matched_slot_spheres(scene.boxes)
        elif uses_pointcloud:
            assert pointcloud_proxies is not None
            obstacle_centers = pointcloud_proxies.centers
            obstacle_params = pointcloud_proxies.sphere_radii.copy()
            if apply_surface_cover:
                assert proxy_offsets is not None
                obstacle_params += proxy_offsets
            rmax = max(float(proxy.radius) for proxy in robot_proxies)
            obstacle_index = MultilevelVoxelTable.from_spheres(
                obstacle_centers,
                obstacle_params,
                voxel_size=rmax + 0.003,
                query_padding=0.16,
            )
        else:
            obstacle_centers, obstacle_params, _ = sample_box_sphere_tree(scene.boxes)
        controller = LiuQPController(
            model,
            data,
            scene,
            robot_proxies,
            obstacle_centers,
            obstacle_params,
            obstacle_index=obstacle_index,
        )
    else:
        if robot_geometry == "full-ellipsoid":
            robot_proxies = build_robot_ellipsoid_certificate(
                model, axial_overlap_factor=2.0
            )
        else:
            robot_proxies = spheres_as_isotropic_ellipsoids(
                build_robot_certificate(model)
            )
        if scene.name == "robust_slot":
            obstacle_centers, obstacle_params, _ = sample_matched_slot_ellipsoids(scene.boxes)
        elif uses_pointcloud:
            assert pointcloud_proxies is not None
            obstacle_centers = pointcloud_proxies.centers
            obstacle_params = pointcloud_proxies.ellipsoid_shapes
            obstacle_offsets = (
                proxy_offsets.copy()
                if apply_surface_cover
                else np.zeros(len(obstacle_centers))
            )
            robot_rmax = max(float(np.max(proxy.semi_axes)) for proxy in robot_proxies)
            obstacle_index = MultilevelVoxelTable.from_ellipsoids(
                obstacle_centers,
                obstacle_params,
                voxel_size=robot_rmax + 0.003,
                query_padding=0.16,
                offset_radii=obstacle_offsets,
            )
        else:
            obstacle_centers, obstacle_params, _ = sample_box_ellipsoid_tree(scene.boxes)
        controller = EllipsoidLiuQPController(
            model,
            data,
            scene,
            robot_proxies,
            obstacle_centers,
            obstacle_params,
            obstacle_offsets=obstacle_offsets if uses_pointcloud else 0.0,
            obstacle_index=obstacle_index,
        )
    controller.objective_dither_std = float(objective_dither_std)
    controller.objective_dither_rng = np.random.default_rng(objective_dither_seed)

    targets = [np.asarray(scene.waypoints[-1])]
    if guidance_targets_override is not None:
        targets = [np.asarray(point, dtype=float) for point in guidance_targets_override]
        if not targets or not np.allclose(targets[-1], scene.waypoints[-1]):
            targets.append(np.asarray(scene.waypoints[-1], dtype=float))
    elif guidance == "prescribed":
        targets = [np.asarray(point) for point in scene.waypoints]
    target_source = target_source_override or (
        "final_goal_only" if guidance == "direct" else "locally_authored_waypoints"
    )
    target_index = 0
    final_target = np.asarray(scene.waypoints[-1])
    steps = int(round(run_duration / DT))
    rows: list[dict[str, float | int | str]] = []
    qdots: list[np.ndarray] = []
    started = time.perf_counter()
    for step in range(steps):
        target = targets[target_index]
        ee_before = attachment_position(model, data)
        if (
            np.linalg.norm(target - ee_before) <= guidance_switch_tolerance
            and target_index + 1 < len(targets)
        ):
            target_index += 1
            target = targets[target_index]
        qdot, metrics = controller.solve(target)
        if certificate == "sphere":
            scale, clearance = integrate_with_safety_backtracking(
                model,
                data,
                qdot,
                robot_proxies,
                obstacle_centers,
                obstacle_params,
                controller.safety_margin,
            )
        else:
            scale, clearance = integrate_ellipsoid_with_backtracking(
                model,
                data,
                qdot,
                robot_proxies,
                obstacle_centers,
                obstacle_params,
                controller.safety_margin,
                controller,
            )
        ee = attachment_position(model, data)
        world_contact = minimum_mujoco_world_contact(data, model)
        self_contact = minimum_mujoco_self_contact(data, model)
        row = metrics.as_dict()
        row.update(
            {
                "step": step,
                "time_s": step * DT,
                "certificate": certificate,
                "robot_certificate_geometry": (
                    "sphere" if certificate == "sphere" else robot_geometry
                ),
                "guidance": guidance,
                "target_source": target_source,
                "target_index": target_index,
                "target_x": float(target[0]),
                "target_y": float(target[1]),
                "target_z": float(target[2]),
                "ee_x": float(ee[0]),
                "ee_y": float(ee[1]),
                "ee_z": float(ee[2]),
                "final_target_error_m": float(np.linalg.norm(final_target - ee)),
                "accepted_step_scale": scale,
                "certificate_clearance_m": clearance,
                "mujoco_world_contact_dist_m": world_contact,
                "mujoco_self_contact_dist_m": self_contact,
            }
        )
        for index, value in enumerate(qdot, start=1):
            row[f"qdot{index}_rad_s"] = float(value)
        for index, value in enumerate(data.qpos[:6], start=1):
            row[f"q{index}_rad"] = float(value)
        rows.append(row)
        qdots.append(np.asarray(qdot, dtype=float))
        if np.linalg.norm(final_target - ee) < goal_tolerance and step > 10:
            if all(
                float(previous["final_target_error_m"]) < goal_tolerance
                for previous in rows[-10:]
            ):
                break

    elapsed = time.perf_counter() - started
    csv_path = output_dir / "trajectory.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)

    final_error = float(rows[-1]["final_target_error_m"])
    certificate_min = float(min(float(row["certificate_clearance_m"]) for row in rows))
    finite_world = [
        float(row["mujoco_world_contact_dist_m"])
        for row in rows
        if np.isfinite(float(row["mujoco_world_contact_dist_m"]))
    ]
    finite_self = [
        float(row["mujoco_self_contact_dist_m"])
        for row in rows
        if np.isfinite(float(row["mujoco_self_contact_dist_m"]))
    ]
    recent = rows[-min(100, len(rows)) :]
    recent_progress = float(recent[0]["final_target_error_m"]) - float(recent[-1]["final_target_error_m"])
    recent_qdot_rms = float(np.sqrt(np.mean(np.asarray(qdots[-len(recent) :]) ** 2)))
    active = np.asarray([int(row["active_obstacle_rows"]) for row in rows])
    raw_key = "raw_obstacle_spheres" if certificate == "sphere" else "raw_obstacle_proxies"
    raw = np.asarray([int(row[raw_key]) for row in rows])
    broadphase = np.asarray(
        [int(row.get("broadphase_candidate_pairs", row[raw_key])) for row in rows]
    )
    solved_fraction = float(np.mean([str(row["status"]).startswith("solved") for row in rows]))
    exact_min_world = float(min(finite_world)) if finite_world else None
    exact_min_self = float(min(finite_self)) if finite_self else None
    exact_safe = (exact_min_world is None or exact_min_world >= -1.0e-7) and (
        exact_min_self is None or exact_min_self >= -1.0e-7
    )
    summary: dict[str, float | int | str | bool | None] = {
        "scene": scene.name,
        "scene_description": scene.description,
        "certificate": certificate,
        "robot_certificate_geometry": (
            "sphere" if certificate == "sphere" else robot_geometry
        ),
        "guidance": guidance,
        "target_source": target_source,
        "guidance_target_count": len(targets),
        "guidance_switch_tolerance_m": float(guidance_switch_tolerance),
        "success": bool(
            final_error < goal_tolerance
            and certificate_min >= -2.0e-5
            and exact_safe
        ),
        "stalled": bool(final_error >= goal_tolerance and recent_progress < 0.001),
        "goal_tolerance_m": float(goal_tolerance),
        "steps": len(rows),
        "simulated_time_s": float(rows[-1]["time_s"]),
        "configured_duration_s": run_duration,
        "wall_time_s": float(elapsed),
        "final_error_m": final_error,
        "recent_goal_progress_m": recent_progress,
        "recent_qdot_rms_rad_s": recent_qdot_rms,
        "qdot_sign_flip_rate": _oscillation_rate(np.asarray(qdots)),
        "minimum_certificate_clearance_m": certificate_min,
        "minimum_mujoco_world_contact_distance_m": exact_min_world,
        "minimum_mujoco_self_contact_distance_m": exact_min_self,
        "solved_qp_fraction": solved_fraction,
        "mean_qp_solve_ms": float(np.mean([float(row["solve_ms"]) for row in rows])),
        "p95_qp_solve_ms": float(np.percentile([float(row["solve_ms"]) for row in rows], 95)),
        "robot_proxies": len(robot_proxies),
        "obstacle_proxies": len(obstacle_centers),
        "mean_unpruned_pairs": float(np.mean(raw)),
        "mean_broadphase_candidate_pairs": float(np.mean(broadphase)),
        "mean_broadphase_reduction_fraction": float(1.0 - np.mean(broadphase / raw)),
        "mean_active_hyperplanes": float(np.mean(active)),
        "mean_reduction_fraction": float(1.0 - np.mean(active / raw)),
        "max_near_penalty_terms": int(max(int(row["near_penalty_terms"]) for row in rows)),
        "max_contact_repulsion_rows": int(max(int(row["contact_repulsion_rows"]) for row in rows)),
        "minimum_accepted_step_scale": float(min(float(row["accepted_step_scale"]) for row in rows)),
        "objective_dither_std": float(objective_dither_std),
        "objective_dither_seed": int(objective_dither_seed),
    }
    if pointcloud_proxies is not None:
        summary.update(
            {
                "obstacle_source": "unlabelled_surface_point_cloud_center_voxel_filtered",
                "pointcloud_proxy_fit": "connected_normal_component_pca_scaled_to_maximum_point_mahalanobis_radius",
                "pointcloud_uncertainty_handling": (
                    "continuous_surface_minkowski_offset_plus_controller_safety_margin"
                    if apply_surface_cover
                    else "controller_safety_margin_only"
                ),
                "raw_point_count": len(pointcloud_proxies.raw_points),
                "filtered_point_count": len(pointcloud_proxies.filtered_points),
                "matched_proxy_count": len(pointcloud_proxies.centers),
                "pointcloud_cluster_size_m": pointcloud_cluster_size,
                "pointcloud_maximum_overshoot_limit_m": pointcloud_maximum_overshoot,
                "pointcloud_point_spacing_m": pointcloud_point_spacing,
                "pointcloud_filter_size_m": pointcloud_filter_size,
                "surface_cover_applied": apply_surface_cover,
                "surface_cover_radius_m": pointcloud_proxies.surface_cover_radius,
                "mean_proxy_offset_radius_m": (
                    float(np.mean(proxy_offsets))
                    if proxy_offsets is not None and len(proxy_offsets)
                    else 0.0
                ),
                "maximum_proxy_offset_radius_m": (
                    float(np.max(proxy_offsets))
                    if proxy_offsets is not None and len(proxy_offsets)
                    else 0.0
                ),
                "surface_validation_spacing_m": pointcloud_proxies.validation_spacing,
                "surface_validation_sampled_max_distance_m": (
                    pointcloud_proxies.validation_sampled_max_distance
                ),
                "surface_validation_lipschitz_correction_m": (
                    pointcloud_proxies.validation_lipschitz_correction
                ),
                "maximum_ellipsoid_aabb_overshoot_m": (
                    pointcloud_proxies.maximum_ellipsoid_overshoot
                ),
                "mvt_voxel_size_m": obstacle_index.stats.voxel_size,
                "mvt_occupied_cells": obstacle_index.stats.occupied_cells,
                "mvt_proxy_cell_references": obstacle_index.stats.proxy_cell_references,
            }
        )
    (output_dir / "summary.json").write_text(
        json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    return summary


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scene", choices=("all", *ABLATION_SCENES), default="drawer")
    parser.add_argument("--certificate", choices=("both", "sphere", "ellipsoid"), default="both")
    parser.add_argument("--guidance", choices=("direct", "prescribed"), default="direct")
    parser.add_argument(
        "--robot-geometry",
        choices=("sphere-limit", "full-ellipsoid"),
        default="sphere-limit",
        help="Robot proxy used with obstacle ellipsoids; sphere-limit is the fair obstacle-only ablation.",
    )
    parser.add_argument(
        "--pointcloud-cluster-size",
        type=float,
        default=0.040,
        help="Shelf-drawer point-cloud proxy bucket size in metres.",
    )
    parser.add_argument(
        "--pointcloud-maximum-overshoot",
        type=float,
        default=0.020,
        help="Maximum fitted-ellipsoid AABB protrusion before recursive splitting.",
    )
    parser.add_argument(
        "--pointcloud-point-spacing",
        type=float,
        default=0.012,
        help="Synthetic depth-surface sampling spacing in metres.",
    )
    parser.add_argument(
        "--pointcloud-filter-size",
        type=float,
        default=0.012,
        help="CenterVox filter size in metres.",
    )
    parser.add_argument(
        "--no-surface-cover",
        action="store_true",
        help="Disable the certified continuous-surface offset (exploratory only).",
    )
    parser.add_argument(
        "--duration",
        type=float,
        default=None,
        help="Optional simulation duration override in seconds.",
    )
    args = parser.parse_args()
    scenes = list(ABLATION_SCENES) if args.scene == "all" else [args.scene]
    certificates = ("sphere", "ellipsoid") if args.certificate == "both" else (args.certificate,)
    summaries = []
    for scene_name in scenes:
        for certificate in certificates:
            summary = run_scene(
                ABLATION_SCENES[scene_name],
                certificate,
                args.guidance,
                args.robot_geometry,
                pointcloud_cluster_size=args.pointcloud_cluster_size,
                pointcloud_maximum_overshoot=args.pointcloud_maximum_overshoot,
                pointcloud_point_spacing=args.pointcloud_point_spacing,
                pointcloud_filter_size=args.pointcloud_filter_size,
                apply_surface_cover=not args.no_surface_cover,
                duration_override=args.duration,
            )
            summaries.append(summary)
            print(json.dumps(summary, indent=2, ensure_ascii=False))
    RESULTS_ROOT.mkdir(parents=True, exist_ok=True)
    (
        RESULTS_ROOT
        / f"summary_{args.scene}_{args.certificate}_{args.robot_geometry}_{args.guidance}.json"
    ).write_text(
        json.dumps(summaries, indent=2, ensure_ascii=False), encoding="utf-8"
    )


if __name__ == "__main__":
    main()
